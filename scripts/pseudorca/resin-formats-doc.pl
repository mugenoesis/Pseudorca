#!/usr/bin/env perl
# Writes docs/resin-formats.md from resources/resin/index.json: which file formats Pseudorca writes, which printers use
# them and which printers still wait for a writer.
#
# usage: resin-formats-doc.pl <resources/resin/index.json> > docs/resin-formats.md
use strict;
use warnings;
use JSON::PP;

my ($file) = @ARGV;
open(my $fh, '<', $file) or die "$file: $!";
my $index = decode_json(do { local $/; <$fh> });

# What each writer is, and whether anybody has printed with it. Update the last column after real prints.
my %notes = (
    CTB          => ['Chitubox CTB, version 4',                      'untested'],
    CTBGKTWO     => ['Chitubox CTB, UniFormation GKtwo variant',     'untested'],
    CTBENCRYPTED => ['Chitubox CTB, encrypted version 5',            'untested'],
    CBDDLP       => ['Chitubox CBDDLP / Photon, version 2',          'untested'],
    GOO          => ['Elegoo GOO, version 3.0',                      'untested'],
    CXDLP        => ['Creality CXDLP, version 3',                    'untested'],
    SVGX         => ['FlashForge SVGX',                              'untested'],
    PHROZENZIP   => ['Phrozen zip (numbered PNGs)',                  'untested'],
    CHITUBOXZIP  => ['Chitubox zip (run.gcode and PNGs)',            'untested'],
    TINYMAKER    => ['TinyMaker image folder (zip)',                 'untested'],
);

my (%by_format, %printers);
for my $p (@{ $index->{printers} }) {
    push @{ $by_format{ $p->{format} } }, "$p->{vendor} $p->{model}";
    $printers{ $p->{supported} ? 'yes' : 'no' }++;
}

print "# Resin printer formats\n\n";
print "Generated by `scripts/pseudorca/resin-formats-doc.pl` from `resources/resin/index.json`. ";
print "$printers{yes} of ", ($printers{yes} + ($printers{no} // 0)), " catalogued printers can be sliced for.\n\n";
print "**No writer has been checked on a real printer yet** except where the last column says so. If you try one, please report\n";
print "the printer, the file format and whether the file loaded and printed.\n\n";
print "## Formats we write\n\n| Format id | What it is | Printers | Printed on hardware |\n|---|---|---|---|\n";
for my $id (sort grep { $notes{$_} || !/^[a-z0-9]+$/ || 1 } keys %by_format) {
    my $supported = grep { $_->{format} eq $id && $_->{supported} } @{ $index->{printers} };
    next unless $supported;
    my ($what, $state) = @{ $notes{$id} // [ "Anycubic Photon Workshop (.$id)", 'untested' ] };
    printf "| `%s` | %s | %d | %s |\n", $id, $what, scalar @{ $by_format{$id} }, $state;
}
print "\n## Printers whose format is not written yet\n\n| Format | Printers |\n|---|---|\n";
for my $id (sort keys %by_format) {
    my $supported = grep { $_->{format} eq $id && $_->{supported} } @{ $index->{printers} };
    next if $supported;
    printf "| `%s` | %s |\n", $id, join(', ', sort @{ $by_format{$id} });
}
