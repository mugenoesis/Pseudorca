void ChituboxZipArchive::export_print(const std::string     fname,
                                      const SLAPrint       &print,
                                      const ThumbnailsList &thumbnails,
                                      const std::string    &projectname)
{
    const SLAMaterialConfig    &mat = print.material_config();
    const SLAPrintObjectConfig &obj = print.default_object_config();
    const auto &levels = print.print_layers();
    const size_t layer_count = std::min(m_layers.size(), levels.size());
    const SLAPrinterConfig &cfg = this->cfg();

    chituzip::GCodeParams p;
    p.file_name = projectname.empty() ? boost::filesystem::path(fname).stem().string() : projectname;
    p.machine_type = cfg.printer_model.value.empty() ? std::string("Default") : cfg.printer_model.value;
    p.layer_height_mm = float(obj.layer_height.getFloat());
    double w = cfg.display_width.getFloat(), h = cfg.display_height.getFloat();
    size_t pw = size_t(cfg.display_pixels_x.getInt()), ph = size_t(cfg.display_pixels_y.getInt());
    if (cfg.display_orientation.getInt() == sla::RasterBase::roPortrait) {
        std::swap(w, h);
        std::swap(pw, ph);
    }
    p.res_x = uint32_t(pw); p.res_y = uint32_t(ph);
    p.machine_x_mm = float(w); p.machine_y_mm = float(h); p.machine_z_mm = cfg.printable_height.getFloat();
    p.mirror = cfg.display_mirror_x.getBool();
    p.exposure_s = float(mat.exposure_time.getFloat());
    p.bottom_exposure_s = float(mat.initial_exposure_time.getFloat());
    p.bottom_layer_count = uint32_t(std::clamp<size_t>(size_t(std::max(0, mat.bottom_layer_count.getInt())), 0, layer_count));
    p.lift_mm = p.bottom_lift_mm = float(mat.lift_distance.getFloat());
    p.lift_mm_min = p.bottom_lift_mm_min = float(mat.lift_speed.getFloat());
    p.retract_mm_min = float(mat.retract_speed.getFloat());
    p.light_off_s = p.bottom_light_off_s = float(mat.delay_before_exposure.get_at(0));
    p.pwm = p.bottom_pwm = uint32_t(std::clamp(mat.light_pwm.getInt(), 0, 255));
    const SLAPrintStatistics &stats = print.print_statistics();
    p.volume_ml = float((stats.objects_used_material + stats.support_used_material) / 1000.);
    p.weight_g = p.volume_ml * float(mat.material_density.getFloat());
    const double bottle_ml = mat.bottle_volume.getFloat();
    p.price = bottle_ml > 0. ? float(p.volume_ml * mat.bottle_cost.getFloat() / bottle_ml) : 0.f;

    const size_t transition = std::min<size_t>(size_t(std::max(0, obj.faded_layers.getInt())), layer_count - p.bottom_layer_count);
    double time_s = 0.;
    for (size_t i = 0; i < layer_count; ++i) {
        chituzip::LayerParams l;
        l.z_mm = float(unscaled<double>(levels[i].level()));
        if (i < p.bottom_layer_count) {
            l.exposure_s = p.bottom_exposure_s;
        } else if (i < size_t(p.bottom_layer_count) + transition) {
            const double k = double(i - p.bottom_layer_count + 1) / double(transition + 1);
            l.exposure_s = float(p.bottom_exposure_s + (p.exposure_s - p.bottom_exposure_s) * k);
        } else {
            l.exposure_s = p.exposure_s;
        }
        l.wait_before_cure_s = p.light_off_s;
        l.wait_after_cure_s = float(mat.delay_after_exposure.get_at(0));
        l.lift_mm = p.lift_mm; l.lift_mm_min = p.lift_mm_min; l.retract_mm_min = p.retract_mm_min;
        l.pwm = p.pwm;
        p.layers.push_back(l);
        time_s += l.exposure_s + l.wait_before_cure_s + l.wait_after_cure_s;
        if (l.lift_mm_min > 0.f) time_s += l.lift_mm / l.lift_mm_min * 60. * 2.;
    }
    p.print_time_s = float(std::ceil(time_s));
    const std::string gcode = chituzip::build_gcode(p);

    try {
        Zipper zipper{fname, Zipper::FAST_COMPRESSION};
        zipper.add_entry("run.gcode", reinterpret_cast<const std::uint8_t*>(gcode.data()), gcode.size());
        if (! thumbnails.empty() && thumbnails.front().is_valid()) {
            add_preview(zipper, "preview.png", thumbnails.front(), 954, 850);
            add_preview(zipper, "preview_cropping.png", thumbnails.front(), 168, 150);
        }
        size_t i = 1;
        for (const sla::EncodedRaster &rst : m_layers)
            zipper.add_entry((std::to_string(i++) + "." + rst.extension()).c_str(), rst.data(), rst.size());
        zipper.finalize();
    } catch (const std::exception &e) {
        BOOST_LOG_TRIVIAL(error) << e.what();
        throw;
    }
}

